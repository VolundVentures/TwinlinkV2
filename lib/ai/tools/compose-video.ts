export const composeVideoTool: ToolHandler = async (
  input,
  context,
  emitter
): Promise<ToolResult> => {
  const rawClipsInput = input.clips as Array<{
    shot_id?: string;
    url?: string;
    type?: "video" | "image";
    label?: string;
    duration_seconds?: number;
    has_own_audio?: boolean;
    is_lipsync?: boolean;
  }>;

  // ── URL RESOLUTION (added 2026-05-12) ─────────────────────────────────
  // The agent reads project state and sees shots as @tags / shot_ids — the
  // state block does NOT surface their public_url. Previously, that forced
  // the agent to invent URLs and compose_video would reject every call.
  // Now: if a clip is passed with just a shot_id (or with an @-prefixed
  // "url" that's really a tag), we look up the actual rendered video URL
  // from generation_assets and substitute it. The agent can pass either
  // shot_id alone OR shot_id + url and we use whichever resolves.
  let rawClips: typeof rawClipsInput;
  {
    const needsResolve = rawClipsInput.filter(
      (c) =>
        c.shot_id &&
        (!c.url || c.url.startsWith("@") || !c.url.startsWith("http"))
    );
    if (needsResolve.length > 0) {
      // Fetch every shot asset for this generation in one query, then map by
      // metadata.shot_id. Latest-by-shot_id wins (handles re-shoots).
      const { data: rows } = await db
        .from("generation_assets")
        .select("id, type, public_url, asset_role, metadata, created_at")
        .eq("generation_id", context.generationId)
        .eq("type", "video")
        .order("created_at", { ascending: false });
      const byShotId = new Map<string, string>();
      for (const r of (rows || []) as Array<{
        public_url: string | null;
        asset_role: string | null;
        metadata: Record<string, unknown> | null;
      }>) {
        const meta = (r.metadata as Record<string, unknown>) || {};
        const sid = meta.shot_id as string | undefined;
        const role = r.asset_role || (meta.role as string | undefined);
        if (sid && role === "shot" && r.public_url && !byShotId.has(sid)) {
          byShotId.set(sid, r.public_url);
        }
      }
      // Also support the keyframe-as-image_clip path: if a shot wasn't
      // rendered as a video but has a hero keyframe, use that as an image.
      const { data: kfRows } = await db
        .from("generation_assets")
        .select("public_url, asset_role, metadata")
        .eq("generation_id", context.generationId)
        .eq("type", "image")
        .eq("asset_role", "keyframe");
      const kfByShotId = new Map<string, string>();
      for (const r of (kfRows || []) as Array<{
        public_url: string | null;
        metadata: Record<string, unknown> | null;
      }>) {
        const meta = (r.metadata as Record<string, unknown>) || {};
        const sid = meta.shot_id as string | undefined;
        if (sid && r.public_url && !kfByShotId.has(sid)) {
          kfByShotId.set(sid, r.public_url);
        }
      }
      rawClips = rawClipsInput.map((c) => {
        if (c.url && c.url.startsWith("http")) return c;
        if (!c.shot_id) return c;
        const videoUrl = byShotId.get(c.shot_id);
        if (videoUrl) {
          return { ...c, url: videoUrl, type: c.type ?? "video" };
        }
        const kfUrl = kfByShotId.get(c.shot_id);
        if (kfUrl) {
          // Fallback: shot wasn't rendered as video, use keyframe as still.
          return { ...c, url: kfUrl, type: "image" as const };
        }
        return c; // unresolved — the validator below will report
      });
      const resolved = rawClips.filter(
        (c, i) => rawClips[i] !== rawClipsInput[i]
      ).length;
      if (resolved > 0) {
        console.log(
          `[tool:compose_video] resolved ${resolved}/${rawClipsInput.length} clip URL(s) from shot_id`
        );
      }
    } else {
      rawClips = rawClipsInput;
    }
  }

  // Sort by shot_id ascending so the cut respects the script regardless of the
  // order the agent built its clips array in. shot_ids look like "shot_1", "shot_2".
  function shotIdOrder(s?: string): number {
    if (!s) return Number.POSITIVE_INFINITY;
    const m = s.match(/(\d+)/);
    return m ? parseInt(m[1], 10) : Number.POSITIVE_INFINITY;
  }
  const clips = [...rawClips].sort((a, b) => shotIdOrder(a.shot_id) - shotIdOrder(b.shot_id));
  console.log(
    "[tool:compose_video] Clip order after shot_id sort:",
    clips.map((c) => `${c.shot_id || "?"}:${c.label || c.type}`).join(" → ")
  );
  const voiceoverUrl = input.voiceover_url as string | undefined;
  const backgroundMusicUrl = input.background_music_url as string | undefined;
  const ambientSoundUrl = input.ambient_sound_url as string | undefined;
  const textOverlays = input.text_overlays as Array<{
    text: string;
    position: string;
    start_seconds?: number;
    end_seconds?: number;
    font_size?: number;
    color?: string;
  }> | undefined;
  const captionSegments = input.caption_segments as Array<{
    text: string;
    start_seconds: number;
    end_seconds: number;
  }> | undefined;
  // Captions OFF by default — agent must explicitly enable for UGC
  const addCaptions = input.captions === true;
  const transition = (input.transition as string) || "crossfade";
  // User's UI choice is the source of truth. Agent input is a fallback only —
  // this prevents the agent from silently rendering 9:16 when the user picked 16:9.
  const aspectRatio =
    context.aspectRatio || (input.aspect_ratio as string) || "";
  const VALID_ASPECTS = new Set(["16:9", "9:16", "1:1", "21:9", "4:3", "3:4"]);
  if (!VALID_ASPECTS.has(aspectRatio)) {
    return {
      success: false,
      content: `compose_video received invalid aspect_ratio "${aspectRatio}". The film spec was not propagated from the user's brief. Must be one of: 16:9, 9:16, 1:1, 21:9, 4:3, 3:4.`,
    };
  }
  if (input.aspect_ratio && context.aspectRatio && input.aspect_ratio !== context.aspectRatio) {
    console.warn(
      `[tool:compose_video] aspect_ratio mismatch — agent passed ${input.aspect_ratio} but user chose ${context.aspectRatio}. Using user choice.`
    );
  }
  const letterbox = (input.letterbox as string) || "none";
  const addWatermark = (input.brand_watermark as boolean) || false;
  const voiceoverDurationSeconds = input.voiceover_duration_seconds as number | undefined;

  const fps = 30;

  console.log(
    "[tool:compose_video]",
    "clips:", clips.length,
    "transition:", transition,
    "aspect:", aspectRatio,
    "captions:", addCaptions,
    "watermark:", addWatermark,
    "voiceover:", voiceoverUrl ? voiceoverUrl.slice(0, 60) : "NONE",
    "music:", backgroundMusicUrl ? backgroundMusicUrl.slice(0, 60) : "NONE",
    "ambient:", ambientSoundUrl ? ambientSoundUrl.slice(0, 60) : "NONE"
  );

  // Validate inputs early
  if (!clips || clips.length === 0) {
    return {
      success: false,
      content: "compose_video requires at least one clip. Generate video or image assets first, then pass their URLs.",
    };
  }

  const invalidClips = clips.filter((c) => !c.url || !c.url.startsWith("http"));
  if (invalidClips.length > 0) {
    const failedIds = invalidClips.map((c) => c.shot_id || "?").join(", ");
    return {
      success: false,
      content: `${invalidClips.length} clip(s) could not be resolved to a video / keyframe URL (shot_id: ${failedIds}). The compose tool now auto-resolves shot_id → URL from the DB — if it still failed, that shot is genuinely missing both a rendered video AND a hero keyframe. Render the shot or its keyframe first, then retry compose.`,
    };
  }

  // Image clips ARE permitted — they correspond to Shot.model === "image_clip"
  // (a deliberate held still, or a graceful fallback to the hero keyframe when
  // the shot's video wasn't rendered). Remotion's AdComposition handles both
  // video and image clip types natively. The previous strict-video check
  // blocked legitimate compose runs.
  const stillCount = clips.filter((c) => c.type !== "video").length;
  if (stillCount > 0) {
    console.log(
      `[tool:compose_video] ${stillCount}/${clips.length} clips are held stills (image_clip or keyframe-fallback).`
    );
  }

  const missingShotId = clips.filter((c) => !c.shot_id);
  if (missingShotId.length > 0) {
    return {
      success: false,
      content: `${missingShotId.length} clip(s) missing shot_id. Every clip must include its shot_id from write_script so the timeline orders correctly.`,
    };
  }

  // Pre-compose validation — WARN on missing music but don't block
  // Blocking caused deadlocks when the score failed — better to have video without music than no video
  if (!backgroundMusicUrl) {
    console.warn("[tool:compose_video] WARNING: No background_music_url. Video will have no background music.");
  }

  // Cinematic films are often intentionally near-silent (music + sparse SFX).
  // If the director chose no VO, no music, and clips have no baked audio — warn but don't block.
  if (!voiceoverUrl && !backgroundMusicUrl && clips.every((c) => !c.has_own_audio)) {
    console.warn(
      "[tool:compose_video] Heads-up: no VO, no music, and all clips are silent. Final film will be silent. If this isn't intentional, call generate_music and/or generate_voiceover first."
    );
  }

  // Validate clip durations exist
  const clipsWithoutDuration = clips.filter(c => !c.duration_seconds);
  if (clipsWithoutDuration.length > 0) {
    return {
      success: false,
      content: `${clipsWithoutDuration.length} clip(s) missing duration_seconds. ALL clips MUST have explicit duration_seconds to prevent audio sync issues. Set each clip's duration to match its actual video length.`,
    };
  }

  // Validate voiceover/clip duration alignment
  const totalClipSeconds = clips.reduce((sum, c) => sum + (c.duration_seconds || 5), 0);
  if (voiceoverUrl && voiceoverDurationSeconds) {
    if (voiceoverDurationSeconds > totalClipSeconds + 3) {
      console.warn(`[tool:compose_video] DURATION MISMATCH: VO=${voiceoverDurationSeconds}s but clips=${totalClipSeconds}s. Voiceover will be cut off.`);
    }
  }

  emitter.send("tool_progress", {
    tool: "compose_video",
    generationId: context.generationId,
    status: "generating",
    message: `Composing ${clips.length} clips into a finished video...`,
  });

  try {
    // Build Remotion inputProps. After URL resolution + the validator above,
    // every clip is guaranteed to have a string url; the assertions silence
    // the now-optional types from the input schema.
    const compositionClips = clips.map((clip) => {
      return {
        url: clip.url as string,
        type: (clip.type ?? "video") as "video" | "image",
        durationFrames: Math.round((clip.duration_seconds || 5) * fps),
        label: clip.label || "clip",
        hasOwnAudio: clip.has_own_audio !== false && (clip.type ?? "video") === "video",
        isLipsync: clip.is_lipsync === true,
      };
    });

    console.log("[tool:compose_video] Clip order (after shot_id sort):", compositionClips.map((c) => `${c.label}(${c.hasOwnAudio ? "native-audio" : "silent"})`).join(" → "));

    const compositionProps: AdCompositionProps = {
      clips: compositionClips,
      transition: transition as AdCompositionProps["transition"],
      fps,
      letterbox: letterbox as AdCompositionProps["letterbox"],
      // aspectRatio drives calculateMetadata's width/height override. The
      // deployed Remotion site only needs ONE composition ID (AdComposition)
      // — aspect is resolved from inputProps at render time.
      aspectRatio: aspectRatio as AdCompositionProps["aspectRatio"],
    };

    // Voiceover — starts at frame 0, plays continuously.
    // Remotion's voiceoverVolume function automatically mutes during has_own_audio clips.
    if (voiceoverUrl) {
      const voDurationFrames = voiceoverDurationSeconds ? Math.round(voiceoverDurationSeconds * fps) : undefined;
      compositionProps.audio = {
        url: voiceoverUrl,
        volume: 0.85,
        startFrame: 0,
        durationFrames: voDurationFrames,
      };

      // Warn about duration mismatch
      const totalClipSeconds = clips.reduce((sum, c) => sum + (c.duration_seconds || 5), 0);
      if (voiceoverDurationSeconds && Math.abs(totalClipSeconds - voiceoverDurationSeconds) > 3) {
        console.warn(
          `[tool:compose_video] DURATION MISMATCH: clips=${totalClipSeconds}s, VO=${voiceoverDurationSeconds}s (diff=${Math.abs(totalClipSeconds - voiceoverDurationSeconds).toFixed(1)}s)`
        );
      }
    }

    // Background music — professional ratio: voice at -12 LUFS, music at -20 LUFS (8 LU gap)
    // In linear scale: voice=0.85 (~-1.4dB), music=0.15 (~-16dB)
    // Music volume relative to voice should be ~6-8x quieter
    if (backgroundMusicUrl) {
      compositionProps.backgroundMusic = {
        url: backgroundMusicUrl,
        volume: 0.15, // Professional broadcast ratio: ~8 LU below voiceover
      };
    }

    // Ambient sound bed — room tone / location texture. Sits BELOW music so
    // the mix layers VO (0.85) > music (0.15) > ambient (0.18, but on a
    // separate track that survives music swells because ambient is broadband
    // texture, not melody). When music is absent the ambient becomes the
    // primary soundscape; we don't bump volume in that case — the AI text-
    // to-sound output is usually loud enough at 0.18 to ground the scene.
    if (ambientSoundUrl) {
      compositionProps.ambientSound = {
        url: ambientSoundUrl,
        volume: 0.18,
      };
    }

    // Text overlays
    if (textOverlays && textOverlays.length > 0) {
      const totalDurationSeconds = clips.reduce(
        (sum, c) => sum + (c.duration_seconds || 5),
        0
      );
      compositionProps.textOverlays = textOverlays.map((overlay) => ({
        text: overlay.text,
        position: overlay.position as "top" | "center" | "bottom",
        startFrame: Math.round((overlay.start_seconds || 0) * fps),
        endFrame: Math.round(
          (overlay.end_seconds || totalDurationSeconds) * fps
        ),
        style: {
          fontSize: overlay.font_size || 48,
          color: overlay.color || "#FFFFFF",
          fontFamily: context.brand?.font_family || "Inter",
          fontWeight: "700",
        },
      }));
    }

    // Generate captions — script segments only
    let captionWords: CaptionWord[] | undefined;
    if (addCaptions) {
      if (captionSegments && captionSegments.length > 0) {
        // PREFERRED: Use script-based captions 
        // Convert script segments into word-level captions
        emitter.send("tool_progress", {
          tool: "compose_video",
          generationId: context.generationId,
          status: "generating",
          message: "Building captions from script...",
        });

        captionWords = [];
        for (const segment of captionSegments) {
          const words = segment.text.split(/\s+/).filter(w => w.length > 0);
          if (words.length === 0) continue;
          const segmentDurationMs = (segment.end_seconds - segment.start_seconds) * 1000;
          const wordDurationMs = segmentDurationMs / words.length;

          for (let i = 0; i < words.length; i++) {
            captionWords.push({
              word: words[i],
              startMs: Math.round(segment.start_seconds * 1000 + i * wordDurationMs),
              endMs: Math.round(segment.start_seconds * 1000 + (i + 1) * wordDurationMs),
            });
          }
        }
        compositionProps.captions = captionWords;
        console.log(`[tool:compose_video] Script-based captions: ${captionWords.length} words from ${captionSegments.length} segments`);
      }
    }

    // Brand watermark
    if (addWatermark && context.brand) {
      compositionProps.brandWatermark = {
        text: context.brand.name,
        logoUrl: context.brand.logo_url || undefined,
        color: "#FFFFFF",
        position: "bottom-right",
      };
    }

    // ALWAYS render via the single AdComposition id. Dimensions are
    // resolved at render-time from inputProps.aspectRatio via
    // calculateAdMetadata. This eliminates the per-aspect composition
    // lookup (which silently fell back to the default 9:16 composition
    // when the deployed S3 site was out of sync).
    const compositionId = "AdComposition";

    emitter.send("tool_progress", {
      tool: "compose_video",
      generationId: context.generationId,
      status: "generating",
      message: "Rendering composed video via Remotion...",
    });

    // Render via Remotion Lambda
    const result = await renderComposition({
      compositionId,
      inputProps: compositionProps as unknown as Record<string, unknown>,
      format: "mp4",
      generationId: context.generationId,
    });

    console.log("[tool:compose_video] Render complete:", result.url.slice(0, 80));

    emitter.send("tool_progress", {
      tool: "compose_video",
      generationId: context.generationId,
      status: "saving",
      message: "Saving composed video...",
    });

    // Save to generation_assets
    const variantNum = await getNextVariantNumber(context.generationId);
    const { data: asset, error: saveError } = await db
      .from("generation_assets")
      .insert({
        generation_id: context.generationId,
        org_id: context.orgId,
        type: "video",
        aspect_ratio: aspectRatio,
        storage_path: result.url,
        public_url: result.url,
        metadata: {
          role: "final_film",
          asset_category: "composed_video",
          source_clips: clips.map((c) => ({
            url: c.url,
            type: c.type,
            label: c.label,
          })),
          transition,
          has_captions: !!captionWords,
          has_watermark: addWatermark,
          has_voiceover: !!voiceoverUrl,
          has_music: !!backgroundMusicUrl,
          text_overlay_count: textOverlays?.length || 0,
          render_duration_ms: result.durationMs,
          composition_id: compositionId,
        },
        variant_number: variantNum,
      })
      .select("id")
      .single();

    if (saveError) {
      console.warn("[tool:compose_video] Failed to save:", saveError.message);
    }

    emitter.send("tool_progress", {
      tool: "compose_video",
      generationId: context.generationId,
      status: "complete",
      message: "Video composed successfully",
    });

    const totalDuration = clips.reduce(
      (sum, c) => sum + (c.duration_seconds || 5),
      0
    );

    const summary = [
      `Composed video created successfully (${aspectRatio}, ~${totalDuration}s)`,
      `URL: ${result.url}`,
      `Clips: ${clips.length} (${clips.map((c) => c.label || c.type).join(", ")})`,
      `Transition: ${transition}`,
      addCaptions && captionWords
        ? `Captions: ${captionWords.length} words transcribed`
        : null,
      addWatermark ? `Watermark: ${context.brand?.name}` : null,
      textOverlays?.length
        ? `Text overlays: ${textOverlays.length}`
        : null,
      voiceoverUrl ? `Voiceover: ${voiceoverUrl.slice(0, 60)}...` : null,
      backgroundMusicUrl ? `Background music: ${backgroundMusicUrl.slice(0, 60)}...` : null,
    ]
      .filter(Boolean)
      .join("\n");

    return {
      success: true,
      content: summary,
      data: { url: result.url, aspectRatio, durationSeconds: totalDuration },
      assets: [
        {
          assetId: asset?.id,
          type: "video",
          url: result.url,
          metadata: {
            role: "final_film", // critical — the director UI routes to FinalView on this
            asset_category: "composed_video",
            aspect_ratio: aspectRatio,
            duration_seconds: totalDuration,
            transition,
            letterbox,
          },
        },
      ],
    };
  } catch (error) {
    const errMsg = error instanceof Error ? error.message : String(error);
    console.error("[tool:compose_video] Error:", errMsg);

    // Provide actionable context
    let hint = "";
    if (errMsg.includes("REMOTION_FUNCTION_NAME") || errMsg.includes("REMOTION_SERVE_URL")) {
      hint = " Hint: Remotion Lambda is not configured. Set REMOTION_FUNCTION_NAME and REMOTION_SERVE_URL in .env.";
    } else if (errMsg.includes("timeout")) {
      hint = " Hint: Remotion render timed out. Try fewer clips or shorter duration.";
    } else if (errMsg.includes("render failed")) {
      hint = " Hint: The Remotion composition crashed during rendering. Check that all clip URLs are accessible and valid.";
    }

    // Log clip details for debugging
    console.error("[tool:compose_video] Clip details:", JSON.stringify(clips.map(c => ({
      url: c.url?.slice(0, 60),
      type: c.type,
      duration: c.duration_seconds,
    }))));

    return {
      success: false,
      content: `Video composition failed: ${errMsg}${hint}`,
    };
  }
};
